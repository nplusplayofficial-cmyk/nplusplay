-- Explicitly owner-approved release activation for all six virtual-demo games.
-- Does not fabricate an authenticated Admin identity and never touches user/wallet/ledger rows.
-- Entire operation is transactional and aborts if any server component or invariant is missing.

BEGIN;

CREATE TABLE IF NOT EXISTS public.nplus_release_operations_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  performed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  operation text NOT NULL,
  performed_by text NOT NULL,
  authorization_basis text NOT NULL,
  deployment_commit text NOT NULL,
  previous_state jsonb NOT NULL,
  new_state jsonb NOT NULL,
  notes text NOT NULL
);

ALTER TABLE public.nplus_release_operations_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.nplus_release_operations_audit FROM PUBLIC, anon, authenticated;

DO $preflight$
DECLARE
  v_expected text[] := ARRAY['5D','AVIATOR','K3','MOTO','TRX','WINGO'];
  v_count integer;
  v_old_state jsonb;
  v_new_state jsonb;
  v_changed integer;
  v_now timestamptz := clock_timestamp();
  v_negative integer;
  v_ledger_mismatch integer;
  v_latest_mismatch integer;
BEGIN
  LOCK TABLE public.game_settings IN SHARE ROW EXCLUSIVE MODE;

  IF (SELECT count(*) FROM public.game_settings) <> 6
     OR (SELECT count(*) FROM public.game_settings WHERE game_key=ANY(v_expected)) <> 6 THEN
    RAISE EXCEPTION 'Activation aborted: game_settings does not contain exactly the six expected release games.';
  END IF;

  IF EXISTS (SELECT 1 FROM public.game_settings WHERE enabled IS DISTINCT FROM false) THEN
    RAISE EXCEPTION 'Activation aborted: expected all six game flags to be OFF before this one-time release operation.';
  END IF;

  -- K3, 5D, TRX: server-owned outcomes/bets/settlement and authenticated RPCs.
  IF to_regclass('public.nplus_demo_lottery_rounds') IS NULL
     OR to_regclass('public.nplus_demo_lottery_bets') IS NULL
     OR to_regprocedure('public.nplus_demo_lottery_snapshot(text,integer)') IS NULL
     OR to_regprocedure('public.nplus_demo_lottery_place_bet(text,integer,text,text,numeric,uuid)') IS NULL THEN
    RAISE EXCEPTION 'Activation aborted: K3/5D/TRX server settlement is incomplete.';
  END IF;

  -- WINGO: required server-side round, bet and settlement RPCs.
  IF to_regclass('public.nplus_wingo_demo_rounds') IS NULL
     OR to_regprocedure('public.nplus_wingo_demo_current_round(integer)') IS NULL
     OR to_regprocedure('public.nplus_wingo_demo_place_bet(integer,jsonb,numeric,uuid)') IS NULL
     OR to_regprocedure('public.nplus_wingo_demo_settle_round(integer,bigint)') IS NULL THEN
    RAISE EXCEPTION 'Activation aborted: WINGO server settlement is incomplete.';
  END IF;

  -- MOTO: required server-side round, bet and settlement RPCs.
  IF to_regclass('public.nplus_moto_demo_rounds') IS NULL
     OR to_regprocedure('public.nplus_moto_demo_current_round()') IS NULL
     OR to_regprocedure('public.nplus_moto_demo_place_bet(jsonb,numeric,uuid)') IS NULL
     OR to_regprocedure('public.nplus_moto_demo_settle_round(bigint)') IS NULL THEN
    RAISE EXCEPTION 'Activation aborted: MOTO server settlement is incomplete.';
  END IF;

  -- AVIATOR: server worker plus a live, healthy scheduler.
  IF to_regclass('public.nplus_aviator_demo_rounds') IS NULL
     OR to_regclass('public.nplus_aviator_worker_health') IS NULL
     OR to_regprocedure('public.nplus_aviator_demo_current_round()') IS NULL
     OR to_regprocedure('public.nplus_aviator_demo_place_bet(uuid,integer,numeric,uuid,numeric)') IS NULL
     OR to_regprocedure('public.nplus_aviator_demo_worker_tick()') IS NULL
     OR NOT EXISTS (
       SELECT 1 FROM cron.job
       WHERE jobname='nplus-aviator-worker' AND database=current_database() AND active
     )
     OR NOT EXISTS (
       SELECT 1 FROM public.nplus_aviator_worker_health
       WHERE singleton_key=true
         AND last_error IS NULL
         AND consecutive_failures=0
         AND last_success_at > v_now-interval '2 minutes'
     ) THEN
    RAISE EXCEPTION 'Activation aborted: AVIATOR worker/scheduler is not healthy.';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.nplus_demo_lottery_rounds
    WHERE status NOT IN ('open','settled')
  ) OR EXISTS (
    SELECT 1 FROM public.nplus_demo_lottery_bets
    WHERE status NOT IN ('pending','won','lost')
  ) THEN
    RAISE EXCEPTION 'Activation aborted: lottery settlement contains an unknown status.';
  END IF;

  SELECT count(*) INTO v_negative FROM public.demo_wallets WHERE balance<0;
  SELECT count(*) INTO v_ledger_mismatch FROM public.demo_wallet_transactions
    WHERE round(balance_before+delta,2)<>round(balance_after,2);
  SELECT count(*) INTO v_latest_mismatch
  FROM public.demo_wallets w
  WHERE w.balance IS DISTINCT FROM (
    SELECT t.balance_after
    FROM public.demo_wallet_transactions t
    WHERE t.user_id=w.user_id
    ORDER BY t.created_at DESC,t.id DESC
    LIMIT 1
  );

  IF v_negative<>0 OR v_ledger_mismatch<>0 OR v_latest_mismatch<>0 THEN
    RAISE EXCEPTION 'Activation aborted: wallet invariants failed (negative %, ledger mismatch %, latest mismatch %).',
      v_negative,v_ledger_mismatch,v_latest_mismatch;
  END IF;

  SELECT jsonb_agg(jsonb_build_object('game_key',game_key,'enabled',enabled) ORDER BY game_key)
    INTO v_old_state FROM public.game_settings;

  UPDATE public.game_settings
  SET enabled=true,
      updated_at=clock_timestamp(),
      -- This was a privileged release operation, not an authenticated Admin click.
      -- Keep the user-attribution field NULL rather than attribute it to an Admin.
      updated_by=NULL
  WHERE game_key=ANY(v_expected) AND enabled=false;
  GET DIAGNOSTICS v_changed=ROW_COUNT;

  IF v_changed<>6 THEN
    RAISE EXCEPTION 'Activation aborted: expected to enable 6 games, changed %.',v_changed;
  END IF;

  SELECT jsonb_agg(jsonb_build_object('game_key',game_key,'enabled',enabled) ORDER BY game_key)
    INTO v_new_state FROM public.game_settings;

  INSERT INTO public.nplus_release_operations_audit
    (operation,performed_by,authorization_basis,deployment_commit,previous_state,new_state,notes)
  VALUES
    ('enable_all_six_demo_games','privileged_release_migration',
     'User explicitly requested final completion and approved activation of all six demo games in this conversation.',
     'c2e4440a04127f63c4ea71b6a76fce05ab91c402',
     v_old_state,v_new_state,
     'Virtual/non-redeemable demo points only. No real-money betting or cash payout. Preflight verified all six server components, Aviator worker/scheduler health, and zero wallet/ledger invariant failures. No existing profiles, wallets, ledger rows, deposits, or referral rows were changed.');

  IF EXISTS (SELECT 1 FROM public.game_settings WHERE game_key=ANY(v_expected) AND enabled IS DISTINCT FROM true) THEN
    RAISE EXCEPTION 'Activation aborted: final game flag verification failed.';
  END IF;
END
$preflight$;

COMMIT;
