-- Aviator server-owned virtual-credit round and bet records.
-- Draft-only; use an isolated database for testing before any deployment.
begin;
create table if not exists public.nplus_aviator_demo_rounds (
  id uuid primary key default gen_random_uuid(),
  round_index bigint generated by default as identity unique,
  created_at timestamptz not null default now(),
  flight_starts_at timestamptz not null,
  crashes_at timestamptz not null,
  crash_point numeric(8,2) not null check (crash_point >= 1.01 and crash_point <= 1000),
  status text not null default 'waiting' check (status in ('waiting','flying','crashed')),
  crashed_at timestamptz,
  check (crashes_at > flight_starts_at),
  check ((status='crashed' and crashed_at is not null) or (status<>'crashed' and crashed_at is null))
);
create index if not exists nplus_aviator_rounds_status_idx
  on public.nplus_aviator_demo_rounds(status,round_index desc);
create table if not exists public.nplus_aviator_demo_bets (
  id uuid primary key default gen_random_uuid(),
  round_id uuid not null references public.nplus_aviator_demo_rounds(id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete restrict,
  request_id uuid not null,
  slot smallint not null check (slot in (0,1)),
  stake numeric(12,2) not null check (stake >= 1 and stake <= 100000),
  auto_cashout numeric(8,2) check (auto_cashout is null or (auto_cashout >= 1.01 and auto_cashout <= 1000)),
  status text not null default 'open' check (status in ('open','cashed_out','lost')),
  cashout_multiplier numeric(8,2),
  payout numeric(12,2) not null default 0 check (payout >= 0),
  created_at timestamptz not null default now(),
  settled_at timestamptz,
  unique(user_id,request_id),
  unique(round_id,user_id,slot),
  check (
    (status='open' and settled_at is null)
    or (status in ('cashed_out','lost') and settled_at is not null)
  ),
  check (
    (status='cashed_out' and cashout_multiplier is not null)
    or (status<>'cashed_out' and cashout_multiplier is null)
  )
);
create index if not exists nplus_aviator_bets_round_status_idx
  on public.nplus_aviator_demo_bets(round_id,status);
create index if not exists nplus_aviator_bets_user_created_idx
  on public.nplus_aviator_demo_bets(user_id,created_at desc);
alter table public.nplus_aviator_demo_rounds enable row level security;
alter table public.nplus_aviator_demo_bets enable row level security;
revoke all on table public.nplus_aviator_demo_rounds from public,anon,authenticated;
revoke all on table public.nplus_aviator_demo_bets from public,anon,authenticated;
commit;
